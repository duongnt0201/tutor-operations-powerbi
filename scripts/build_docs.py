"""Build docs/data-model.md and docs/measures.md from the TMDL definition.

Usage: python scripts/build_docs.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEF = ROOT / "powerbi" / "TutorOperations.SemanticModel" / "definition"
DOCS = ROOT / "docs"
SKIP = ("LocalDateTable_", "DateTableTemplate_")


def parse_tables():
    tables = {}
    for f in sorted((DEF / "tables").glob("*.tmdl")):
        if f.name.startswith(SKIP):
            continue
        s = f.read_text(encoding="utf-8")
        name = re.search(r"^table (.+)$", s, re.M).group(1).strip().strip("'")
        cols, measures = [], []
        for m in re.finditer(r"^\t(column|measure) (.+?)(?: =(.*))?$\n((?:\t\t.*\n|[ \t]*\n)*)", s, re.M):
            kind, obj, inline, body = m.group(1), m.group(2).strip().strip("'"), (m.group(3) or "").strip(), m.group(4)
            dt = re.search(r"^\t\tdataType: (\w+)", body, re.M)
            fmt = re.search(r"^\t\tformatString: (.+)$", body, re.M)
            folder = re.search(r"^\t\tdisplayFolder: (.+)$", body, re.M)
            expr = inline
            if not expr or expr == "```":
                lines = [l[3:] for l in body.split("\n") if l.startswith("\t\t\t")]
                expr = "\n".join(lines).strip().strip("`").strip()
            item = dict(name=obj, dataType=dt.group(1) if dt else "", expr=expr,
                        fmt=fmt.group(1) if fmt else "", folder=folder.group(1) if folder else "")
            if kind == "column":
                item["calc"] = m.group(3) is not None
                cols.append(item)
            else:
                measures.append(item)
        part = re.search(r"partition .+? = (\w+)", s)
        tables[name] = dict(cols=cols, measures=measures, kind=part.group(1) if part else "")
    return tables


def parse_relationships():
    s = (DEF / "relationships.tmdl").read_text(encoding="utf-8")
    rels = []
    for block in s.split("\nrelationship ")[1:]:
        g = lambda k: (re.search(rf"^\t{k}: (.+)$", block, re.M) or [None, ""])[1].strip()
        if "LocalDateTable" in block:
            continue
        rels.append(dict(frm=g("fromColumn"), to=g("toColumn"), active=g("isActive") != "false",
                         both=g("crossFilteringBehavior") == "bothDirections",
                         card=f"{g('fromCardinality') or 'many'}:{g('toCardinality') or 'one'}"))
    return rels


def mermaid_id(t):
    return re.sub(r"\W", "_", t)


def build_model(tables, rels):
    out = ["# Data model", "", "> Generated by `scripts/build_docs.py` from the TMDL definition.", "",
           "## Relationship diagram", "", "```mermaid", "erDiagram"]
    used = set()
    for r in rels:
        ft, fc = r["frm"].split(".", 1)
        tt, tc = r["to"].split(".", 1)
        used |= {ft, tt}
        left = "}o" if r["card"].startswith("many") else "||"
        right = "o{" if r["card"].endswith("many") else "||"
        line = "--" if r["active"] else ".."
        label = fc.strip("'") + (" (both)" if r["both"] else "") + ("" if r["active"] else " (inactive)")
        out.append(f'    {mermaid_id(tt)} {right[::-1].replace("{", "}")}{line}{left[::-1].replace("}", "{")} {mermaid_id(ft)} : "{label}"')
    out += ["```", "", "## Tables", "", "| Table | Type | Columns | Calculated columns | Measures |", "|---|---|---|---|---|"]
    for t, v in tables.items():
        kind = "Fact" if t.startswith("fact_") else "Dimension" if t.startswith("dim_") else \
            "Parameter" if t.startswith("para") else "Measure table" if "Measure" in t else "Helper"
        out.append(f"| `{t}` | {kind} | {sum(not c['calc'] for c in v['cols'])} | {sum(c['calc'] for c in v['cols'])} | {len(v['measures'])} |")
    out += ["", "## Columns", ""]
    for t, v in tables.items():
        if not v["cols"]:
            continue
        out += [f"### {t}", "", "| Column | Type | Calculated |", "|---|---|---|"]
        out += [f"| `{c['name']}` | {c['dataType'] or '-'} | {'yes' if c['calc'] else ''} |" for c in v["cols"]]
        out.append("")
    out += ["## Relationships", "", "| From | To | Cardinality | Cross filter | Active |", "|---|---|---|---|---|"]
    out += [f"| `{r['frm']}` | `{r['to']}` | {r['card']} | {'both' if r['both'] else 'single'} | {'yes' if r['active'] else 'no'} |"
            for r in rels]
    (DOCS / "data-model.md").write_text("\n".join(out) + "\n", encoding="utf-8")


def build_measures(tables):
    out = ["# Measure dictionary", "", "> Generated by `scripts/build_docs.py` from the TMDL definition.", ""]
    total = sum(len(v["measures"]) for v in tables.values())
    out += [f"Total measures: **{total}**", ""]
    for t, v in tables.items():
        if not v["measures"]:
            continue
        out += [f"## {t}", ""]
        for m in v["measures"]:
            out += [f"### {m['name']}", ""]
            if m["fmt"]:
                out += [f"Format: `{m['fmt']}`", ""]
            out += ["```dax", m["expr"], "```", ""]
    (DOCS / "measures.md").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    DOCS.mkdir(exist_ok=True)
    tables, rels = parse_tables(), parse_relationships()
    build_model(tables, rels)
    build_measures(tables)
    print(f"tables={len(tables)} relationships={len(rels)} measures={sum(len(v['measures']) for v in tables.values())}")
